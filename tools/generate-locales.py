"""Generate the shared UI phrase catalog for React and Compose; no runtime network."""
from pathlib import Path
import json
root = Path(__file__).resolve().parent.parent
catalog = {}
for line in (root / 'shared/translations-sw.txt').read_text().splitlines():
    if ' => ' in line:
        source, target = line.split(' => ', 1)
        catalog[source] = target
payload = json.dumps(catalog, ensure_ascii=False, indent=2) + '\n'
(root / 'shared/translations-sw.json').write_text(payload)
(root / 'web/src/lib/sw.json').write_text(payload)
compact = json.dumps(catalog, ensure_ascii=False, separators=(',', ':')).replace('$', "${'$'}")
(root / 'app/src/main/java/com/biashara/app/ui/LocaleCatalog.kt').write_text('''package com.biashara.app.ui

import org.json.JSONObject

// Generated by tools/generate-locales.py from the shared phrase catalog.
private val swCatalog by lazy { JSONObject("""''' + compact + '''""") }
private val swLower by lazy { swCatalog.keys().asSequence().associate { it.lowercase() to swCatalog.getString(it) } }
fun tr(text: String): String {
    if (AppLanguage != "sw") return text
    val clean = text.trim().replace(Regex("""\\s+"""), " ")
    val translated = swCatalog.optString(clean, "").ifBlank { swLower[clean.lowercase()] ?: "" }
    if (translated.isNotBlank()) return text.replace(text.trim(), if (clean == clean.uppercase()) translated.uppercase() else translated)
    return text
}
''')
print(f'Generated {len(catalog)} shared phrases.')
