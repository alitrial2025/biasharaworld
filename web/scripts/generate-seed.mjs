import ts from "typescript";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
const toolRequire = createRequire(import.meta.url);
const cache = {};
function load(file) {
  file = path.resolve(file);
  if (cache[file]) return cache[file].exports;
  const output = { exports: {} };
  cache[file] = output;
  const code = ts.transpileModule(fs.readFileSync(file, "utf8"), {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
  }).outputText;
  new Function("require", "module", "exports", code)(
    (name) => {
      if (name.startsWith("."))
        return load(path.resolve(path.dirname(file), name + ".ts"));
      return toolRequire(name);
    },
    output,
    output.exports,
  );
  return output.exports;
}
const seed = load("src/lib/data.ts").initialState();
const payload = JSON.stringify({
  products: seed.products,
  operations: seed.operations,
});
fs.mkdirSync("../shared", { recursive: true });
fs.writeFileSync(
  "../shared/demo-seed-v2.json",
  JSON.stringify(
    { products: seed.products, operations: seed.operations },
    null,
    2,
  ) + "\n",
);
fs.writeFileSync(
  "../app/src/main/java/com/biashara/app/data/OperationsSeed.kt",
  'package com.biashara.app.data\n\n// Generated by web/scripts/generate-seed.mjs; dates are refreshed at first use.\ninternal const val OPERATIONS_SEED = """' +
    payload +
    '"""\n',
);
console.log("Shared demo fixture and Kotlin seed generated.");
